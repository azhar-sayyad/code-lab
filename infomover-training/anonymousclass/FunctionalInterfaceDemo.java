package com.imt.training.java.anonymousclass;

/**
* <p> Lambda expression provides implementation of functional interface. </p>
* An interface which has only one abstract method is called functional interface.
* Java provides an anotation @FunctionalInterface, which is used to declare an interface as functional interface.</p>
*
 */
@FunctionalInterface
public interface FunctionalInterfaceDemo {
    void fun();
}
